    public static String decode(String text) {
        StringBuilder out = new StringBuilder();
        for (int i = 0; i < text.length(); i++) {
            if (text.charAt(i) == '&') {
                int end = text.indexOf(';', i + 1);
                if (end > i && end - i < 32) {
                    String name = text.substring(i + 1, end); Integer value = ENTITIES.get(name);
                    try {
                        if (name.startsWith("#x") || name.startsWith("#X")) value = Integer.parseInt(name.substring(2), 16);
                        else if (name.startsWith("#")) value = Integer.parseInt(name.substring(1));
                    } catch (NumberFormatException ignored) { value = null; }
                    if (value != null && value > 0 && value <= 0x10ffff && (value < 0xd800 || value > 0xdfff)) {
                        out.appendCodePoint(value); i = end; continue;
                    }
                }
            }
            out.append(text.charAt(i));
        }
        return out.toString();
    }
